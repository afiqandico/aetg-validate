def render_html(report: Dict[str, Any]) -> str:
    """Self-contained HTML (inline CSS, no external assets, no JS)."""
    from html import escape

    summary = report["summary"]
    prov = report["provenance"]
    pop = summary["population"]

    rows = [
        ("ESR, Phi-valid (binding)", _fmt_interval(summary.get("esr_phi_pct")).replace("**", "")),
        ("Functional Validity Rate (FVR)", _fmt_interval(summary.get("fvr_pct")).replace("**", "")),
        ("ESR, feature-space (diagnostic)", _fmt_interval(summary.get("esr_feature_space_pct")).replace("**", "")),
    ]
    row_html = "\n".join(
        f"<tr><th>{escape(name)}</th><td>{escape(value)}</td></tr>" for name, value in rows
    )

    tech_html = ""
    techniques = summary.get("techniques") or []
    if techniques:
        body = "\n".join(
            f"<tr><td><code>{escape(str(t['technique']))}</code></td>"
            f"<td>{t['n_total']}</td><td>{t['n_valid']}</td><td>{t['n_escaped']}</td></tr>"
            for t in techniques
        )
        tech_html = (
            "<h2>Per-technique breakdown</h2><table><thead><tr>"
            "<th>Technique</th><th>Produced</th><th>Phi-valid</th><th>Escaped (Phi)</th>"
            f"</tr></thead><tbody>{body}</tbody></table>"
        )

    rules = summary["detection"]["rules_hit"]
    rules_html = ""
    if rules:
        items = "".join(f"<li><code>{escape(rule)}</code></li>" for rule in rules)
        rules_html = f"<h2>Rules that fired</h2><ul>{items}</ul>"

    inputs_html = "".join(
        f"<li><code>{escape(i['path'])}</code> "
        f"<span class='muted'>sha256 {escape(i['sha256'][:16])}… · {i['records']} records</span></li>"
        for i in prov.get("inputs", [])
    )
    sig = report["integrity"].get("signature")
    sig_html = (
        f"<code>{escape(sig['alg'])}</code> = <code>{escape(sig['value'])}</code>"
        if sig
        else "<span class='muted'>none (no signing key configured)</span>"
    )
    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>IDS Evasion Validation — {escape(report['title'])}</title>
<style>{_HTML_CSS}</style></head><body>
<h1>IDS Evasion Validation Report</h1>
<p class="muted">{escape(report['title'])} · generated by <code>{TOOL_NAME}</code>
{escape(prov['tool_version'])} at {escape(prov['timestamp'])} · provenance: {escape(prov['kind'])}</p>
<h2>Binding result</h2>
<table>{row_html}</table>
<div class="binding">
<p>Flows produced <strong>{pop['n_total']}</strong> · Phi-valid <strong>{pop['n_phi_valid']}</strong>
· gate-rejected <strong>{pop['n_gate_rejected']}</strong> · rules fired
<strong>{summary['detection']['rules_hit_count']}</strong></p>
</div>
<div class="warn"><p>The two ESR rows are not interchangeable. The feature-space rate counts
flows that never completed a handshake; only the Phi-valid rate is a defensible claim
about IDS weakness.</p></div>
{tech_html}
{rules_html}
<h2>Integrity</h2>
<p>Measurement digest (reproducible, SHA-256): <code>{escape(report['integrity']['measurement_digest'])}</code><br>
Report digest (includes timestamp and title): <code>{escape(report['integrity']['report_digest'])}</code><br>
Signature over the measurement digest: {sig_html}</p>
<p class="muted">Re-run the same inputs with the same tool version and the measurement
digest must match. If it does not, either the inputs or the code changed.</p>
<h2>Inputs</h2><ul>{inputs_html}</ul>
</body></html>
"""
