"""Report rendering and integrity signing.

A report is useful only if a third party can re-run the scan and get the same
digest. So every report carries:

* the provenance block (tool version, inputs, SHA-256 of each input, seed),
* both evasion rates with their intervals,
* a digest over the canonical JSON payload,
* optionally an HMAC signature when ``AETG_VALIDATE_KEY`` is set.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import os
from datetime import datetime, timezone
from typing import Any, Dict, Optional, Sequence

TOOL_NAME = "aetg-validate"


def canonical_json(payload: Any) -> str:
    """Deterministic JSON: sorted keys, no whitespace variance, ASCII-safe."""
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def digest(payload: Any) -> str:
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


def measurement_payload(
    *,
    tool_version: str,
    kind: str,
    summary: Dict[str, Any],
    inputs: Sequence[Dict[str, Any]],
) -> Dict[str, Any]:
    """The part of a report that must be *reproducible*.

    Deliberately excludes the timestamp, the report title, free-text notes and
    the input **paths**: two people scanning the same bytes on different
    machines must arrive at the same measurement digest, or the reproducibility
    claim is only decoration. Paths are replaced by content hashes.
    """
    return {
        "tool_version": tool_version,
        "kind": kind,
        "summary": summary,
        "inputs": sorted(
            ({"sha256": item["sha256"], "records": item["records"]} for item in inputs),
            key=lambda item: (item["sha256"], item["records"]),
        ),
    }


def measurement_digest(
    *,
    tool_version: str,
    kind: str,
    summary: Dict[str, Any],
    inputs: Sequence[Dict[str, Any]],
) -> str:
    """Digest over everything that a re-run can reproduce."""
    return digest(
        measurement_payload(
            tool_version=tool_version, kind=kind, summary=summary, inputs=inputs
        )
    )


def sign(payload_digest: str, key: Optional[str] = None) -> Optional[Dict[str, str]]:
    """HMAC-SHA256 signature over the payload digest.

    Returns ``None`` when no key is configured — an unsigned report is honest
    about being unsigned rather than silently pretending to be verified.
    """
    if not key:
        return None
    mac = hmac.new(key.encode("utf-8"), payload_digest.encode("utf-8"), hashlib.sha256)
    return {"alg": "hmac-sha256", "value": mac.hexdigest()}


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _fmt_interval(pct: Optional[Dict[str, Any]]) -> str:
    if not pct:
        return "n/a (no Phi-valid flows)"
    return (
        f"**{pct['point_pct']:.2f}%** "
        f"[{pct['low_pct']:.2f}%, {pct['high_pct']:.2f}%] "
        f"({pct['k']}/{pct['n']})"
    )


def render_markdown(report: Dict[str, Any]) -> str:
    """Human-readable report. The Phi-valid number always comes first."""
    summary = report["summary"]
    prov = report["provenance"]
    lines = [
        f"# IDS Evasion Validation Report — {report['title']}",
        "",
        f"*Generated by `{TOOL_NAME}` {prov['tool_version']} at {prov['timestamp']}*",
        f"*Provenance: {prov['kind']}*",
        "",
        "## Binding result",
        "",
        "| Metric | Value (95% Wilson CI) |",
        "|---|---|",
        f"| **ESR, Phi-valid (binding)** | {_fmt_interval(summary.get('esr_phi_pct'))} |",
        f"| Functional Validity Rate (FVR) | {_fmt_interval(summary.get('fvr_pct'))} |",
        f"| ESR, feature-space (diagnostic only) | {_fmt_interval(summary.get('esr_feature_space_pct'))} |",
        "",
        f"- Flows produced: **{summary['population']['n_total']}**",
        f"- Flows passing the functional gate: **{summary['population']['n_phi_valid']}**",
        f"- Flows rejected by the gate: **{summary['population']['n_gate_rejected']}**",
        f"- Distinct IDS rules that fired: **{summary['detection']['rules_hit_count']}**",
    ]
    min_p = summary["detection"]["min_p_ids"]
    if min_p is not None:
        lines.append(f"- Lowest detector confidence observed: **{min_p:.6g}**")

    lines += [
        "",
        "> The two ESR rows are **not** interchangeable. The feature-space rate counts",
        "> flows that never completed a handshake; those are malformed traffic, not",
        "> evasions. Only the Phi-valid rate is a defensible claim about IDS weakness.",
    ]

    techniques = summary.get("techniques") or []
    if techniques:
        lines += ["", "## Per-technique breakdown", "", "| Technique | Produced | Phi-valid | Escaped (Phi) |", "|---|---|---|---|"]
        for row in techniques:
            lines.append(
                f"| `{row['technique']}` | {row['n_total']} | {row['n_valid']} | {row['n_escaped']} |"
            )

    rules = summary["detection"]["rules_hit"]
    if rules:
        lines += ["", "## Rules that fired", ""]
        lines += [f"- `{rule}`" for rule in rules]

    lines += [
        "",
        "## Integrity",
        "",
        f"- Measurement digest (reproducible, SHA-256): `{report['integrity']['measurement_digest']}`",
        f"- Report digest (includes timestamp and title): `{report['integrity']['report_digest']}`",
    ]
    sig = report["integrity"].get("signature")
    if sig:
        lines.append(f"- Signature over the measurement digest: `{sig['alg']}` = `{sig['value']}`")
    else:
        lines.append("- Signature: none (no signing key configured)")

    lines += [
        "",
        "> Re-run the same inputs with the same tool version and the measurement",
        "> digest must match. If it does not, either the inputs or the code changed.",
    ]

    lines += ["", "## Inputs", ""]
    for item in prov.get("inputs", []):
        lines.append(f"- `{item['path']}` — sha256 `{item['sha256'][:16]}…` ({item['records']} records)")
    if prov.get("notes"):
        lines += ["", "## Notes", ""]
        lines += [f"- {note}" for note in prov["notes"]]

    return "\n".join(lines) + "\n"


